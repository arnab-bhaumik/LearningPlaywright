// For Loop
// Help you to repeat a block of code.

// Increment Operator
// ++ -> increase the value 1
// Pre -   ()
let a = 10;
let b = ++a; //(++a ->  10+1)
console.log(b);
console.log(a);


let a1 = 10;
let b1 = a1++;
console.log(b1);
console.log(a1);    